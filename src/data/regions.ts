/** 由地区名反查所属省份 */
export const provinceOfRegion = (region?: string): string => {
  if (!region) return '云南'
  for (const p of PROVINCES) {
    for (const g of p.groups) {
      for (const item of g.items) {
        if (item === region) return p.name
      }
    }
  }
  // 模糊兜底：地区名包含省份关键词
  const direct = ['云南', '贵州', '四川', '重庆', '广西', '西藏', '湖南', '湖北', '广东', '福建',
    '浙江', '江西', '陕西', '甘肃', '海南', '安徽', '河南', '山西', '山东', '河北', '辽宁',
    '吉林', '黑龙江', '江苏', '内蒙古', '宁夏', '青海', '新疆', '北京', '天津', '上海', '台湾']
  for (const p of direct) {
    if (region.includes(p)) return p
  }
  return '云南'
}
